function getTeacher(id) {
	return TEACHERS.find((t) => t.id === id);
}
function teachersByDepartment(list = TEACHERS) {
	const grouped = [];
	for (const dept of DEPARTMENTS) {
		const teachers = list.filter((t) => t.department === dept);
		if (teachers.length) grouped.push({
			department: dept,
			teachers
		});
	}
	return grouped;
}
